#!/usr/bin/env python3
"""Generate selective-build backend adapters and deterministic GPR source lists."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


MAJORS = (14, 15, 16, 17, 18)
VERSION_PATTERN = re.compile(r"(?:-|_)v(14|15|16|17|18)(?:[-_.]|$)")


def write_if_changed(path: Path, contents: str, check: bool) -> None:
    old = path.read_text() if path.exists() else None
    if check:
        if old != contents:
            raise SystemExit(f"generated build-layout file is stale: {path}")
    elif old != contents:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)


def backend_spec(major: int) -> str:
    return f"""--  Generated by tools/generate_build_layout.py.  Do not edit.
package Flyology.Postgres.SQL.Native.Backend_V{major} is
   pragma Elaborate_Body;
end Flyology.Postgres.SQL.Native.Backend_V{major};
"""


def backend_body(major: int) -> str:
    return f"""--  Generated by tools/generate_build_layout.py.  Do not edit.
with Flyology.Postgres.SQL.Native.Backend;
with Flyology.Postgres.SQL.Native.Builders;
with Flyology.Postgres.SQL.Native.Converters;
with Flyology.Postgres.SQL.Native.Schema_V{major};
with Flyology.Postgres.SQL.Native.Version_V{major};

package body Flyology.Postgres.SQL.Native.Backend_V{major} is

   procedure Load
     (Tree   : in out Syntax_Tree;
      Build  : Builders.Builder;
      Root   : Builders.Dynamic_Value;
      Result : out Value_Id) is
   begin
      Converters.Load
        (Tree, Build, Root, Schema_V{major}.Version_Number,
         Schema_V{major}.Node_Message, Schema_V{major}.List_Message,
         Schema_V{major}.Raw_Stmt_Message, Schema_V{major}.Messages,
         Schema_V{major}.Fields, Schema_V{major}.Enums,
         Schema_V{major}.Enum_Values, Result);
   end Load;

   package Registered is new Backend
     (Version      => PostgreSQL_{major},
      Parse_Native => Version_V{major}.Parse,
      Load         => Load);
   pragma Unreferenced (Registered);

end Flyology.Postgres.SQL.Native.Backend_V{major};
"""


def all_versions_spec() -> str:
    return """--  Generated by tools/generate_build_layout.py.  Do not edit.
package Flyology.Postgres.SQL.All_Versions is
   pragma Elaborate_Body;
   --  Elaborating this package registers every versioned shallow parser.
end Flyology.Postgres.SQL.All_Versions;
"""


def all_versions_body() -> str:
    context = []
    for major in MAJORS:
        unit = f"Flyology.Postgres.SQL.Native.Backend_V{major}"
        context.extend((f"with {unit};", f"pragma Elaborate_All ({unit});"))
    return "\n".join(
        [
            "--  Generated by tools/generate_build_layout.py.  Do not edit.",
            *context,
            "",
            "package body Flyology.Postgres.SQL.All_Versions is",
            "end Flyology.Postgres.SQL.All_Versions;",
            "",
        ]
    )


def classify_source(name: str) -> str:
    if "-all_versions.ad" in name:
        return "umbrella"
    match = VERSION_PATTERN.search(name)
    if match:
        return f"v{match.group(1)}"
    return "core"


def source_lists(source_dir: Path) -> dict[str, list[str]]:
    result = {"core": [], "umbrella": []}
    result.update({f"v{major}": [] for major in MAJORS})
    for path in sorted(source_dir.iterdir(), key=lambda item: item.name):
        if path.is_file() and path.suffix in (".ads", ".adb"):
            result[classify_source(path.name)].append(path.name)
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    sql_root = Path(__file__).resolve().parents[1]
    source_dir = sql_root / "src"
    projects_dir = sql_root / "projects"

    for major in MAJORS:
        stem = f"flyology-postgres-sql-native-backend_v{major}"
        write_if_changed(source_dir / f"{stem}.ads", backend_spec(major), args.check)
        write_if_changed(source_dir / f"{stem}.adb", backend_body(major), args.check)

    all_stem = "flyology-postgres-sql-all_versions"
    write_if_changed(source_dir / f"{all_stem}.ads", all_versions_spec(), args.check)
    write_if_changed(source_dir / f"{all_stem}.adb", all_versions_body(), args.check)

    for group, names in source_lists(source_dir).items():
        contents = "".join(f"{name}\n" for name in names)
        write_if_changed(projects_dir / f"{group}.sources", contents, args.check)


if __name__ == "__main__":
    main()
