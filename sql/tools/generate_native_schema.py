#!/usr/bin/env python3
"""Generate the native-Ada-to-public-arena schema from pg_query.proto."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from generate_ada import SCALARS, parse_proto, reachable_schema
from generate_native_actions import clang_ast, enum_values as clang_enum_values


SIGNED = {"int32", "sint32", "sfixed32", "int64", "sint64", "sfixed64"}
UNSIGNED = {"uint32", "fixed32", "uint64", "fixed64"}
FLOATS = {"float", "double"}


def quoted(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def render(major: int, proto: Path, version_header: Path, vendor: Path) -> str:
    all_messages, all_enums = parse_proto(proto)
    messages, enums = reachable_schema(all_messages, all_enums)
    clang_root, _ = clang_ast(vendor)
    source_enums = clang_enum_values(clang_root)
    message_ids = {message.name: index for index, message in enumerate(messages, 1)}
    enum_ids = {enum.name: index for index, enum in enumerate(enums, 1)}
    version_match = re.search(
        r"^#define\s+PG_VERSION_NUM\s+(\d+)\s*$",
        version_header.read_text(),
        re.MULTILINE,
    )
    if version_match is None:
        raise ValueError(f"PG_VERSION_NUM is missing from {version_header}")

    fields = []
    message_rows = []
    for message in messages:
        first = len(fields) + 1
        for field in message.fields:
            if field.type_name in all_messages:
                kind = "Message_Value"
                target = message_ids[field.type_name]
            elif field.type_name in all_enums:
                kind = "Enum_Value"
                target = enum_ids[field.type_name]
            elif field.type_name == "bool":
                kind, target = "Boolean_Value", 0
            elif field.type_name in SIGNED:
                kind, target = "Signed_Value", 0
            elif field.type_name in UNSIGNED:
                kind, target = "Unsigned_Value", 0
            elif field.type_name in FLOATS:
                kind, target = "Float_Value", 0
            elif field.type_name in {"string", "bytes"}:
                kind, target = "Text_Value", 0
            elif field.type_name in SCALARS:
                raise AssertionError(field.type_name)
            else:
                raise ValueError(
                    f"unreachable type {field.type_name} in {message.name}.{field.name}"
                )
            fields.append((field.json_name, field.json_name, kind, target, field.repeated))
        message_rows.append(
            (message.name, source_enums.get("T_" + message.name, -1),
             first, len(message.fields))
        )

    enum_values = []
    enum_rows = []
    for enum in enums:
        first = len(enum_values) + 1
        mapped = [
            (source_enums[name], number, name)
            for name, number in enum.values
            if name in source_enums
        ]
        enum_values.extend(mapped)
        enum_rows.append((first, len(mapped)))

    lines = [
        "--  Generated by tools/generate_native_schema.py.  Do not edit.",
        "pragma Style_Checks (Off);",
        "with Ada.Strings.Unbounded; use Ada.Strings.Unbounded;",
        "with Interfaces;",
        "with Flyology.Postgres.SQL.Native.Schema; use Flyology.Postgres.SQL.Native.Schema;",
        "",
        f"private package Flyology.Postgres.SQL.Native.Schema_V{major} is",
        "",
        "   use type Interfaces.Integer_64;",
        "",
        f"   Version_Number : constant Interfaces.Integer_64 := {version_match.group(1)};",
        f"   Node_Message : constant Positive := {message_ids['Node']};",
        f"   List_Message : constant Positive := {message_ids['List']};",
        f"   Raw_Stmt_Message : constant Positive := {message_ids['RawStmt']};",
        "",
        f"   Messages : constant Message_Array (1 .. {len(message_rows)}) :=",
        "     (",
    ]
    for index, (name, node_tag, first, count) in enumerate(message_rows, 1):
        comma = "," if index < len(message_rows) else ""
        lines.append(
            f"      {index} => (To_Unbounded_String ({quoted(name)}), "
            f"{node_tag}, {first}, {count}){comma}"
        )
    lines.extend(["     );", "", f"   Fields : constant Field_Array (1 .. {len(fields)}) :=", "     ("])
    for index, (source, output, kind, target, repeated) in enumerate(fields, 1):
        comma = "," if index < len(fields) else ""
        lines.append(
            f"      {index} => (To_Unbounded_String ({quoted(source)}), "
            f"To_Unbounded_String ({quoted(output)}), {kind}, {target}, "
            f"{'True' if repeated else 'False'}){comma}"
        )
    lines.extend(["     );", "", f"   Enums : constant Enum_Array (1 .. {len(enum_rows)}) :=", "     ("])
    for index, (first, count) in enumerate(enum_rows, 1):
        comma = "," if index < len(enum_rows) else ""
        lines.append(f"      {index} => ({first}, {count}){comma}")
    lines.extend([
        "     );", "",
        f"   Enum_Values : constant Enum_Value_Array (1 .. {len(enum_values)}) :=",
        "     (",
    ])
    for index, (source_number, wire_number, name) in enumerate(enum_values, 1):
        comma = "," if index < len(enum_values) else ""
        lines.append(
            f"      {index} => ({source_number}, {wire_number}, "
            f"To_Unbounded_String ({quoted(name)})){comma}"
        )
    lines.extend(["     );", "", f"end Flyology.Postgres.SQL.Native.Schema_V{major};", ""])
    return "\n".join(lines)


def write_if_changed(path: Path, content: str, check: bool) -> None:
    old = path.read_text() if path.exists() else None
    if check:
        if old != content:
            raise SystemExit(f"generated native schema is stale: {path}")
    elif old != content:
        path.write_text(content)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--major", type=int, required=True)
    parser.add_argument("--proto", type=Path, required=True)
    parser.add_argument("--version-header", type=Path, required=True)
    parser.add_argument("--vendor", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = args.output / f"flyology-postgres-sql-native-schema_v{args.major}.ads"
    write_if_changed(
        target,
        render(args.major, args.proto, args.version_header, args.vendor),
        args.check,
    )
    if not args.check:
        print(f"generated native PostgreSQL {args.major} arena schema")


if __name__ == "__main__":
    main()
