#!/usr/bin/env python3
"""Generate fully owned Ada PostgreSQL AST records from pg_query.proto."""

from __future__ import annotations

import argparse
from collections import OrderedDict
from pathlib import Path

from generate_ada import (
    SCALARS,
    Enum,
    Field,
    Message,
    accessor_name,
    ada_name,
    enum_literal,
    message_name,
    parse_proto,
    reachable_schema,
    sequence_name,
)


SPECIAL_MESSAGES = {"ParseResult", "Node"}


def access_name(name: str) -> str:
    return message_name(name) + "_Access"


def owned_type(
    field: Field, messages: dict[str, Message], enums: dict[str, Enum]
) -> str:
    if field.type_name in SCALARS:
        if field.type_name in {"string", "bytes"}:
            return "Text"
        return SCALARS[field.type_name]
    if field.type_name in messages:
        return access_name(field.type_name)
    if field.type_name in enums:
        return ada_name(field.type_name)
    raise AssertionError(field.type_name)


def optional_name(
    field: Field, messages: dict[str, Message], enums: dict[str, Enum]
) -> str:
    target = owned_type(field, messages, enums)
    target = target.replace("Interfaces.", "").replace("Standard.", "")
    return "Optional_" + target


def component_type(
    field: Field, messages: dict[str, Message], enums: dict[str, Enum]
) -> str:
    if field.repeated:
        return sequence_name(field, messages, enums)
    return optional_name(field, messages, enums)


def source_view(name: str) -> str:
    return message_name(name)


def convert_record_name(name: str) -> str:
    return "Convert_" + message_name(name)


def convert_access_name(name: str) -> str:
    return convert_record_name(name) + "_Access"


def convert_sequence_name(name: str) -> str:
    return "Convert_" + name


def release_contents_name(name: str) -> str:
    return "Release_Contents_" + message_name(name)


def free_name(name: str) -> str:
    return "Free_" + message_name(name)


def schema_parts(
    messages: list[Message], enums: list[Enum]
) -> tuple[
    dict[str, Message],
    dict[str, Enum],
    list[Message],
    OrderedDict[str, Field],
    OrderedDict[str, Field],
]:
    message_map = {item.name: item for item in messages}
    enum_map = {item.name: item for item in enums}
    node_targets = {field.type_name for field in message_map["Node"].fields}
    concrete = [
        item for item in messages
        if item.name not in SPECIAL_MESSAGES
    ]
    unexpected = {
        item.name for item in concrete
        if item.name != "RawStmt" and item.name not in node_targets
    }
    if unexpected:
        raise ValueError(
            "reachable messages are not represented by Node: "
            + ", ".join(sorted(unexpected))
        )

    repeated: OrderedDict[str, Field] = OrderedDict()
    optionals: OrderedDict[str, Field] = OrderedDict()
    for message in messages:
        if message.name == "Node":
            continue
        for field in message.fields:
            if field.repeated:
                repeated[sequence_name(field, message_map, enum_map)] = field
            else:
                optionals[optional_name(field, message_map, enum_map)] = field
    return message_map, enum_map, concrete, repeated, optionals


def generate_spec(major: int, messages: list[Message], enums: list[Enum]) -> str:
    message_map, enum_map, concrete, repeated, optionals = schema_parts(
        messages, enums
    )
    node = message_map["Node"]
    lines = [
        "--  Generated by tools/generate_owned_ast.py.  Do not edit.",
        "--  The controlled owner finalizes the complete recursive object graph.",
        'pragma Style_Checks ("M160");',
        "with Ada.Containers.Vectors;",
        "with Ada.Finalization;",
        "with Ada.Strings.Unbounded;",
        "with Interfaces;",
        "",
        f"package Flyology.Postgres.SQL.AST.V{major} is",
        "",
    ]
    repeated_scalars = {
        field.type_name for field in repeated.values()
        if field.type_name in SCALARS
    }
    if repeated_scalars & {"string", "bytes"}:
        lines.append("   use type Ada.Strings.Unbounded.Unbounded_String;")
    for type_name in sorted(repeated_scalars - {"string", "bytes"}):
        lines.append(f"   use type {SCALARS[type_name]};")
    if repeated_scalars:
        lines.append("")
    lines.extend([
        "   subtype Text is Ada.Strings.Unbounded.Unbounded_String;",
        "",
    ])

    for enum in enums:
        literals = [enum_literal(enum, value) for value, _ in enum.values]
        lines.append(f"   type {ada_name(enum.name)} is")
        lines.append("     (" + ",\n      ".join(literals) + ");")
        lines.append("")

    kinds = ["No_Node"] + [
        "Node_" + message_name(field.type_name) for field in node.fields
    ]
    lines.append("   type Node_Kind is")
    lines.append("     (" + ",\n      ".join(kinds) + ");")
    lines.extend([
        "",
        "   type Node (Kind : Node_Kind := No_Node);",
        "   type Node_Access is access all Node;",
        "",
    ])
    for message in concrete:
        lines.append(f"   type {message_name(message.name)};")
        lines.append(
            f"   type {access_name(message.name)} is access all "
            f"{message_name(message.name)};"
        )
    lines.append("")

    for name, field in repeated.items():
        element = owned_type(field, message_map, enum_map)
        package_name = name + "_Vectors"
        lines.extend([
            f"   package {package_name} is new Ada.Containers.Vectors",
            f"     (Index_Type => Positive, Element_Type => {element});",
            f"   subtype {name} is {package_name}.Vector;",
            "",
        ])

    for name, field in optionals.items():
        target = owned_type(field, message_map, enum_map)
        lines.extend([
            f"   type {name} (Present : Standard.Boolean := False) is record",
            "      case Present is",
            "         when True =>",
            f"            Value : {target};",
            "         when False =>",
            "            null;",
            "      end case;",
            "   end record;",
            "",
        ])

    for message in messages:
        if message.name == "Node":
            continue
        record_name = message_name(message.name)
        if not message.fields:
            lines.extend([f"   type {record_name} is null record;", ""])
            continue
        declaration = (
            f"   type {record_name} is record"
            if message.name != "ParseResult"
            else f"   type {record_name} is record"
        )
        lines.append(declaration)
        for field in message.fields:
            lines.append(
                f"      {accessor_name(field)} : "
                f"{component_type(field, message_map, enum_map)};"
            )
        lines.extend(["   end record;", ""])

    lines.extend([
        "   type Node (Kind : Node_Kind := No_Node) is record",
        "      case Kind is",
        "         when No_Node =>",
        "            null;",
    ])
    for field in node.fields:
        target = message_name(field.type_name)
        lines.extend([
            f"         when Node_{target} =>",
            f"            {target}_Payload : {target};",
        ])
    lines.extend([
        "      end case;",
        "   end record;",
        "",
        "   type Owned_Syntax_Tree is",
        "     new Ada.Finalization.Limited_Controlled with record",
        "      Valid               : Standard.Boolean := False;",
        "      Source_Text         : Text;",
        "      Diagnostic_Message  : Text;",
        "      Diagnostic_Position : Natural := 0;",
        "      Root                : Parse_Result;",
        "   end record;",
        "",
        "   procedure Clear (Tree : in out Owned_Syntax_Tree);",
        "",
        "   procedure Parse",
        "     (SQL     : String;",
        "      Result  : in out Owned_Syntax_Tree;",
        "      Options : Parse_Options := Default_Options);",
        "   --  Parse native semantic values directly into the owned tree, without",
        "   --  constructing an intermediate public Syntax_Tree arena.",
        "",
        "private",
        "",
        "   procedure Materialize",
        "     (Arena : Syntax_Tree; Result : in out Owned_Syntax_Tree)",
        "     with Pre =>",
        f"       Is_Valid (Arena) and then Version (Arena) = PostgreSQL_{major};",
        "   --  Validation baseline support for the non-installed Testing child.",
        "",
        "   overriding procedure Finalize (Tree : in out Owned_Syntax_Tree);",
        "",
        f"end Flyology.Postgres.SQL.AST.V{major};",
        "",
    ])
    return "\n".join(lines)


def enum_conversion(enum_name: str, expression: str) -> str:
    target = ada_name(enum_name)
    return f"{target}'Val (Shallow.{target}'Pos ({expression}))"


def value_conversion(
    field: Field,
    expression: str,
    message_map: dict[str, Message],
    enum_map: dict[str, Enum],
) -> str:
    if field.type_name in SCALARS:
        return expression
    if field.type_name in message_map:
        if field.type_name == "Node":
            return f"Convert_Node (Arena, {expression})"
        return f"{convert_access_name(field.type_name)} (Arena, {expression})"
    if field.type_name in enum_map:
        return enum_conversion(field.type_name, expression)
    raise AssertionError(field.type_name)


def generate_body(major: int, messages: list[Message], enums: list[Enum]) -> str:
    message_map, enum_map, concrete, repeated, _ = schema_parts(messages, enums)
    node = message_map["Node"]
    access_targets = {
        field.type_name
        for message in messages
        if message.name != "Node"
        for field in message.fields
        if field.type_name in message_map and field.type_name != "Node"
    }
    referenced_concrete = [
        message for message in concrete if message.name in access_targets
    ]
    lines = [
        "--  Generated by tools/generate_owned_ast.py.  Do not edit.",
        "pragma Style_Checks (Off);",
        "with Ada.Unchecked_Deallocation;",
        f"with Flyology.Postgres.SQL.Views.V{major};",
        "",
        f"package body Flyology.Postgres.SQL.AST.V{major} is",
        "",
        f"   package Shallow renames Flyology.Postgres.SQL.Views.V{major};",
        "",
    ]

    lines.extend([
        "   procedure Free_Node is new Ada.Unchecked_Deallocation",
        "     (Object => Node, Name => Node_Access);",
    ])
    for message in referenced_concrete:
        lines.extend([
            f"   procedure {free_name(message.name)} is new Ada.Unchecked_Deallocation",
            f"     (Object => {message_name(message.name)},",
            f"      Name   => {access_name(message.name)});",
        ])
    lines.append("")

    lines.append("   procedure Release (Item : in out Node_Access);")
    for message in referenced_concrete:
        lines.append(
            f"   procedure Release (Item : in out {access_name(message.name)});"
        )
    for message in messages:
        if message.name != "Node":
            lines.append(
                f"   procedure {release_contents_name(message.name)} "
                f"(Item : in out {message_name(message.name)});"
            )
    lines.append("")

    for message in messages:
        if message.name == "Node":
            continue
        record_name = message_name(message.name)
        proc = release_contents_name(message.name)
        lines.extend([
            f"   procedure {proc} (Item : in out {record_name}) is",
            "   begin",
        ])
        if not message.fields:
            lines.append("      null;")
        for field in message.fields:
            component = accessor_name(field)
            if field.repeated:
                if field.type_name in message_map:
                    lines.extend([
                        f"      for Index in Item.{component}.First_Index ..",
                        f"        Item.{component}.Last_Index",
                        "      loop",
                        "         declare",
                        f"            Child : {access_name(field.type_name)} :=",
                        f"              Item.{component}.Element (Index);",
                        "         begin",
                        "            Release (Child);",
                        "         end;",
                        "      end loop;",
                    ])
                lines.append(f"      Item.{component}.Clear;")
            else:
                if field.type_name in message_map:
                    lines.extend([
                        f"      if Item.{component}.Present then",
                        f"         Release (Item.{component}.Value);",
                        "      end if;",
                    ])
                lines.append(
                    f"      Item.{component} := (Present => False);"
                )
        lines.extend([f"   end {proc};", ""])

    for message in referenced_concrete:
        access = access_name(message.name)
        lines.extend([
            f"   procedure Release (Item : in out {access}) is",
            "   begin",
            "      if Item /= null then",
            f"         {release_contents_name(message.name)} (Item.all);",
            f"         {free_name(message.name)} (Item);",
            "      end if;",
            "   end Release;",
            "",
        ])

    lines.extend([
        "   procedure Release (Item : in out Node_Access) is",
        "   begin",
        "      if Item = null then",
        "         return;",
        "      end if;",
        "      case Item.Kind is",
        "         when No_Node =>",
        "            null;",
    ])
    for field in node.fields:
        target = message_name(field.type_name)
        lines.extend([
            f"         when Node_{target} =>",
            f"            {release_contents_name(field.type_name)}",
            f"              (Item.{target}_Payload);",
        ])
    lines.extend([
        "      end case;",
        "      Free_Node (Item);",
        "   end Release;",
        "",
        "   function Convert_Node",
        "     (Arena : Syntax_Tree; Item : Shallow.Node_Reference)",
        "      return Node_Access;",
    ])
    for message in concrete:
        target = message_name(message.name)
        lines.extend([
            f"   function {convert_record_name(message.name)}",
            f"     (Arena : Syntax_Tree; Item : Shallow.{target})",
            f"      return {target};",
        ])
        if message.name in access_targets:
            lines.extend([
            f"   function {convert_access_name(message.name)}",
            f"     (Arena : Syntax_Tree; Item : Shallow.{target}_Reference)",
            f"      return {target}_Access;",
            ])
    lines.append("")

    for name, field in repeated.items():
        source_type = name
        target_type = name
        function_name = convert_sequence_name(name)
        lines.extend([
            f"   function {function_name}",
            f"     (Arena : Syntax_Tree; Items : Shallow.{source_type})",
            f"      return {target_type}",
            "   is",
            f"      Result : {target_type};",
            "   begin",
            "      for Index in 1 .. Shallow.Length (Arena, Items) loop",
        ])
        source = "Shallow.Element (Arena, Items, Index)"
        converted = value_conversion(field, source, message_map, enum_map)
        if field.type_name in message_map:
            element_type = owned_type(field, message_map, enum_map)
            lines.extend([
                "         declare",
                f"            Child : {element_type} := {converted};",
                "         begin",
                "            Result.Append (Child);",
                "         exception",
                "            when others =>",
                "               Release (Child);",
                "               raise;",
                "         end;",
            ])
        else:
            lines.append(f"         Result.Append ({converted});")
        lines.extend([
            "      end loop;",
            "      return Result;",
        ])
        if field.type_name in message_map:
            element_type = owned_type(field, message_map, enum_map)
            lines.extend([
                "   exception",
                "      when others =>",
                "         for Index in Result.First_Index .. Result.Last_Index loop",
                "            declare",
                f"               Child : {element_type} := Result.Element (Index);",
                "            begin",
                "               Release (Child);",
                "            end;",
                "         end loop;",
                "         Result.Clear;",
                "         raise;",
            ])
        lines.extend([f"   end {function_name};", ""])

    for message in concrete:
        target = message_name(message.name)
        record_converter = convert_record_name(message.name)
        access_converter = convert_access_name(message.name)
        lines.extend([
            f"   function {record_converter}",
            f"     (Arena : Syntax_Tree; Item : Shallow.{target})",
            f"      return {target}",
            "   is",
            f"      Result : {target};",
            "   begin",
        ])
        uses_arena = any(
            field.repeated or field.type_name in message_map
            for field in message.fields
        )
        if not uses_arena:
            lines.append("      pragma Unreferenced (Arena);")
        if not message.fields:
            lines.append("      pragma Unreferenced (Item);")
        for field in message.fields:
            component = accessor_name(field)
            if field.repeated:
                expression = (
                    f"{convert_sequence_name(sequence_name(field, message_map, enum_map))}"
                    f" (Arena, Item.{component})"
                )
            else:
                value = value_conversion(
                    field, f"Item.{component}.Value", message_map, enum_map
                )
                expression = (
                    f"(if Item.{component}.Present then "
                    f"(Present => True, Value => {value}) "
                    f"else (Present => False))"
                )
            lines.append(f"      Result.{component} := {expression};")
        lines.extend([
            "      return Result;",
            "   exception",
            "      when others =>",
            f"         {release_contents_name(message.name)} (Result);",
            "         raise;",
            f"   end {record_converter};",
            "",
        ])
        if message.name in access_targets:
            lines.extend([
                f"   function {access_converter}",
                f"     (Arena : Syntax_Tree; Item : Shallow.{target}_Reference)",
                f"      return {target}_Access",
                "   is",
                f"      Value  : {target} :=",
                f"        {record_converter} (Arena, Shallow.View (Arena, Item));",
                f"      Result : {target}_Access;",
                "   begin",
                f"      Result := new {target}'(Value);",
                "      return Result;",
                "   exception",
                "      when others =>",
                f"         {release_contents_name(message.name)} (Value);",
                "         raise;",
                f"   end {access_converter};",
                "",
            ])

    lines.extend([
        "   function Convert_Node",
        "     (Arena : Syntax_Tree; Item : Shallow.Node_Reference)",
        "      return Node_Access",
        "   is",
        "   begin",
        "      case Shallow.Kind (Arena, Item) is",
        "         when Shallow.No_Node =>",
        "            return new Node'(Kind => No_Node);",
    ])
    for field in node.fields:
        target = message_name(field.type_name)
        lines.extend([
            f"         when Shallow.Node_{target} =>",
            "            declare",
            f"               Value : {target} :=",
            f"                 {convert_record_name(field.type_name)}",
            f"                   (Arena, Shallow.View",
            f"                      (Arena, Shallow.As_{target} (Arena, Item)));",
            "               Result : Node_Access;",
            "            begin",
            f"               Result := new Node'",
            f"                 (Kind => Node_{target},",
            f"                  {target}_Payload => Value);",
            "               return Result;",
            "            exception",
            "               when others =>",
            f"                  {release_contents_name(field.type_name)} (Value);",
            "                  raise;",
            "            end;",
        ])
    lines.extend([
        "      end case;",
        "   end Convert_Node;",
        "",
    ])

    parse_result = message_map["ParseResult"]
    lines.extend([
        "   function Convert_Parse_Result",
        "     (Arena : Syntax_Tree) return Parse_Result",
        "   is",
        "      Item : constant Shallow.Parse_Result :=",
        "        Shallow.View (Arena, Shallow.Root (Arena));",
        "      Result : Parse_Result;",
        "   begin",
    ])
    for field in parse_result.fields:
        component = accessor_name(field)
        if field.repeated:
            expression = (
                f"{convert_sequence_name(sequence_name(field, message_map, enum_map))}"
                f" (Arena, Item.{component})"
            )
        else:
            value = value_conversion(
                field, f"Item.{component}.Value", message_map, enum_map
            )
            expression = (
                f"(if Item.{component}.Present then "
                f"(Present => True, Value => {value}) "
                f"else (Present => False))"
            )
        lines.append(f"      Result.{component} := {expression};")
    lines.extend([
        "      return Result;",
        "   exception",
        "      when others =>",
        "         Release_Contents_Parse_Result (Result);",
        "         raise;",
        "   end Convert_Parse_Result;",
        "",
        "   procedure Clear (Tree : in out Owned_Syntax_Tree) is",
        "   begin",
        "      Release_Contents_Parse_Result (Tree.Root);",
        "      Tree.Valid := False;",
        "      Tree.Source_Text := Ada.Strings.Unbounded.Null_Unbounded_String;",
        "      Tree.Diagnostic_Message :=",
        "        Ada.Strings.Unbounded.Null_Unbounded_String;",
        "      Tree.Diagnostic_Position := 0;",
        "   end Clear;",
        "",
        "   overriding procedure Finalize (Tree : in out Owned_Syntax_Tree) is",
        "   begin",
        "      Clear (Tree);",
        "   end Finalize;",
        "",
        "   procedure Materialize",
        "     (Arena : Syntax_Tree; Result : in out Owned_Syntax_Tree) is",
        "   begin",
        "      Clear (Result);",
        "      Result.Source_Text :=",
        "        Ada.Strings.Unbounded.To_Unbounded_String (Source (Arena));",
        "      Result.Root := Convert_Parse_Result (Arena);",
        "      Result.Valid := True;",
        "   exception",
        "      when others =>",
        "         Clear (Result);",
        "         raise;",
        "   end Materialize;",
        "",
        "   procedure Parse",
        "     (SQL     : String;",
        "      Result  : in out Owned_Syntax_Tree;",
        "      Options : Parse_Options := Default_Options) is separate;",
        "",
        f"end Flyology.Postgres.SQL.AST.V{major};",
        "",
    ])
    return "\n".join(lines)


def write_if_changed(path: Path, contents: str, check: bool) -> None:
    old = path.read_text() if path.exists() else None
    if check:
        if old != contents:
            raise SystemExit(f"generated owned AST is stale: {path}")
    elif old != contents:
        path.write_text(contents)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--major", type=int, required=True)
    parser.add_argument("--proto", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    all_messages, all_enums = parse_proto(args.proto)
    messages, enums = reachable_schema(all_messages, all_enums)
    stem = f"flyology-postgres-sql-ast-v{args.major}"
    write_if_changed(
        args.output / f"{stem}.ads",
        generate_spec(args.major, messages, enums),
        args.check,
    )
    write_if_changed(
        args.output / f"{stem}.adb",
        generate_body(args.major, messages, enums),
        args.check,
    )
    print(
        f"{'verified' if args.check else 'generated'} PostgreSQL {args.major} "
        f"owned AST: {len(messages)} messages, {len(enums)} enums"
    )


if __name__ == "__main__":
    main()
