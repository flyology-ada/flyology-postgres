#!/usr/bin/env python3
"""Generate exhaustive structural equality for an owned PostgreSQL AST."""

from __future__ import annotations

import argparse
from pathlib import Path

from generate_ada import SCALARS, Enum, Field, Message, accessor_name, parse_proto, reachable_schema
from generate_owned_ast import access_name, message_name, schema_parts


MAXIMUM_DEPTH = 256
TRACE_MISMATCH = False


def equivalent_name(name: str) -> str:
    return "Equivalent_" + message_name(name)


def value_comparison(
    field: Field,
    left: str,
    right: str,
    messages: dict[str, Message],
    enums: dict[str, Enum],
) -> str:
    if field.type_name == "Node":
        return f"Equivalent_Node ({left}, {right}, Depth + 1)"
    if field.type_name in messages:
        return f"{equivalent_name(field.type_name)} ({left}, {right}, Depth + 1)"
    if field.type_name in SCALARS or field.type_name in enums:
        return f"{left} = {right}"
    raise AssertionError(field.type_name)


def generate(major: int, messages: list[Message], enums: list[Enum]) -> str:
    message_map, enum_map, concrete, _, _ = schema_parts(messages, enums)
    node = message_map["Node"]
    access_targets = {
        field.type_name
        for message in messages if message.name != "Node"
        for field in message.fields
        if field.type_name in message_map and field.type_name != "Node"
    }
    scalar_types = sorted({
        SCALARS[field.type_name]
        for message in messages
        for field in message.fields
        if field.type_name in SCALARS
    })
    lines = [
        "--  Generated by tools/generate_owned_equivalence.py.  Do not edit.",
        "pragma Style_Checks (Off);",
        "with Ada.Containers;",
        "with Ada.Strings.Unbounded;",
        "with Interfaces;",
        *( ["with Ada.Text_IO;"] if TRACE_MISMATCH else [] ),
        "",
        f"separate (Flyology.Postgres.SQL.AST.V{major})",
        "function Equivalent",
        "  (Left, Right : Owned_Syntax_Tree) return Boolean",
        "is",
        "   use type Ada.Containers.Count_Type;",
    ]
    for scalar in scalar_types:
        if scalar == "String":
            continue
        if scalar == "Standard.Boolean":
            continue
        if scalar == "Interfaces.Unsigned_64":
            continue
        lines.append(f"   use type {scalar};")
    lines.extend([
        "   function Fail (Path : String) return Boolean is",
        "   begin",
        *( ["      pragma Unreferenced (Path);"] if not TRACE_MISMATCH else [] ),
        *( ["      Ada.Text_IO.Put_Line (\"owned AST mismatch: \" & Path);"] if TRACE_MISMATCH else [] ),
        "      return False;",
        "   end Fail;",
        "",
        "",
        "   function Equivalent_Node",
        "     (Left, Right : Node_Access; Depth : Natural) return Boolean;",
    ])
    for message in messages:
        if message.name == "Node":
            continue
        target = message_name(message.name)
        if message.name == "ParseResult":
            lines.extend([
                f"   function {equivalent_name(message.name)}",
                f"     (Left, Right : {target}; Depth : Natural) return Boolean;",
            ])
        else:
            if message.name in access_targets:
                lines.extend([
                    f"   function {equivalent_name(message.name)}",
                    f"     (Left, Right : {target}_Access; Depth : Natural) return Boolean;",
                ])
            lines.extend([
                f"   function Equivalent_Record_{target}",
                f"     (Left, Right : {target}; Depth : Natural) return Boolean;",
            ])
    lines.append("")

    for message in messages:
        if message.name == "Node":
            continue
        target = message_name(message.name)
        function = equivalent_name(message.name)
        is_root = message.name == "ParseResult"
        left_prefix = "Left"
        right_prefix = "Right"
        body_function = function if is_root else f"Equivalent_Record_{target}"
        parameters = (
            f"     (Left, Right : {target}; Depth : Natural) return Boolean"
            if is_root else f"     (Left, Right : {target}; Depth : Natural) return Boolean"
        )
        lines.extend([
            f"   function {body_function}",
            parameters,
            "   is",
            "   begin",
            f"      if Depth > {MAXIMUM_DEPTH} then",
            "         raise Constraint_Error with \"excessive owned AST recursion\";",
            "      end if;",
        ])
        if not message.fields:
            lines.append("      pragma Unreferenced (Left, Right);")
        for field in message.fields:
            component = accessor_name(field)
            left = f"{left_prefix}.{component}"
            right = f"{right_prefix}.{component}"
            if field.repeated:
                lines.extend([
                    f"      if {left}.Length /= {right}.Length then",
                    f"         return Fail (\"{target}.{component}.Length\");",
                    "      end if;",
                    f"      for Index in {left}.First_Index .. {left}.Last_Index loop",
                ])
                compared = value_comparison(
                    field,
                    f"{left}.Element (Index)",
                    f"{right}.Element (Index)",
                    message_map,
                    enum_map,
                )
                lines.extend([
                    f"         if not ({compared}) then",
                    f"            return Fail (\"{target}.{component}.Element\");",
                    "         end if;",
                    "      end loop;",
                ])
            else:
                lines.extend([
                    f"      if {left}.Present /= {right}.Present then",
                    f"         return Fail (\"{target}.{component}.Present\");",
                    f"      elsif {left}.Present then",
                ])
                compared = value_comparison(
                    field,
                    f"{left}.Value",
                    f"{right}.Value",
                    message_map,
                    enum_map,
                )
                lines.extend([
                    f"         if not ({compared}) then",
                    f"            return Fail (\"{target}.{component}.Value\");",
                    "         end if;",
                    "      end if;",
                ])
        lines.extend([
            "      return True;",
            f"   end {body_function};",
            "",
        ])
        if not is_root and message.name in access_targets:
            lines.extend([
                f"   function {function}",
                f"     (Left, Right : {target}_Access; Depth : Natural) return Boolean is",
                "   begin",
                "      if Left = null or else Right = null then",
                "         return Left = Right;",
                "      end if;",
                f"      return Equivalent_Record_{target} (Left.all, Right.all, Depth);",
                f"   end {function};",
                "",
            ])

    lines.extend([
        "   function Equivalent_Node",
        "     (Left, Right : Node_Access; Depth : Natural) return Boolean",
        "   is",
        "   begin",
        f"      if Depth > {MAXIMUM_DEPTH} then",
        "         raise Constraint_Error with \"excessive owned AST recursion\";",
        "      end if;",
        "      if Left = null or else Right = null then",
        "         return Left = Right;",
        "      elsif Left.Kind /= Right.Kind then",
        "         return Fail (\"Node.Kind\");",
        "      end if;",
        "      case Left.Kind is",
        "         when No_Node =>",
        "            return True;",
    ])
    for field in node.fields:
        target = message_name(field.type_name)
        lines.extend([
            f"         when Node_{target} =>",
            f"            return Equivalent_Record_{target}",
            f"              (Left => Left.{target}_Payload,",
            f"               Right => Right.{target}_Payload,",
            "               Depth => Depth + 1);",
        ])
    lines.extend([
        "      end case;",
        "   end Equivalent_Node;",
        "",
        "begin",
        "   if Left.Valid /= Right.Valid",
        "     or else Left.Source_Text /= Right.Source_Text",
        "     or else Left.Diagnostic_Message /= Right.Diagnostic_Message",
        "     or else Left.Diagnostic_Position /= Right.Diagnostic_Position",
        "   then",
        "      return Fail (\"Owned_Syntax_Tree metadata\");",
        "   end if;",
        "   return Equivalent_Parse_Result (Left.Root, Right.Root, 0);",
        "end Equivalent;",
        "",
    ])
    return "\n".join(lines)


def write_if_changed(path: Path, contents: str, check: bool) -> None:
    old = path.read_text() if path.exists() else None
    if check:
        if old != contents:
            raise SystemExit(f"generated owned equivalence is stale: {path}")
    elif old != contents:
        path.write_text(contents)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--major", type=int, required=True)
    parser.add_argument("--proto", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    all_messages, all_enums = parse_proto(args.proto)
    messages, enums = reachable_schema(all_messages, all_enums)
    output = args.output / f"flyology-postgres-sql-ast-v{args.major}-equivalent.adb"
    write_if_changed(output, generate(args.major, messages, enums), args.check)
    print(
        f"{'verified' if args.check else 'generated'} PostgreSQL {args.major} "
        "owned AST equivalence"
    )


if __name__ == "__main__":
    main()
