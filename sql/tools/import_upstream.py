#!/usr/bin/env python3
"""Import a pinned standalone PostgreSQL parser extraction.

The input is an unpacked, tagged libpg_query release.  Only raw SQL parsing and
protobuf serialization are retained.  JSON, deparsing, fingerprinting,
normalization, PL/pgSQL entry points, tests, and build products are excluded.

This is a maintainer tool.  Consumer builds compile the checked-in sources and
never access the network.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
from pathlib import Path


VERSIONS = (14, 15, 16, 17, 18)


def digest(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            value.update(chunk)
    return value.hexdigest()


def remove_function(source: str, signature: str) -> str:
    """Remove a C function whose declaration begins with *signature*."""
    start = source.find(signature)
    if start < 0:
        return source
    brace = source.find("{", start)
    if brace < 0:
        raise ValueError(f"opening brace not found for {signature}")
    depth = 0
    cursor = brace
    while cursor < len(source):
        if source[cursor] == "{":
            depth += 1
        elif source[cursor] == "}":
            depth -= 1
            if depth == 0:
                cursor += 1
                while cursor < len(source) and source[cursor] in " \t\r\n":
                    cursor += 1
                return source[:start] + source[cursor:]
        cursor += 1
    raise ValueError(f"closing brace not found for {signature}")


def thin_parse_source(source: str) -> str:
    for signature in (
        "PgQueryParseResult pg_query_parse(",
        "PgQueryParseResult pg_query_parse_opts(",
        "void pg_query_free_parse_result(",
    ):
        source = remove_function(source, signature)
    return source


def wrapper(major: int, has_options: bool) -> str:
    call = (
        "pg_query_parse_protobuf_opts(input, parser_options)"
        if has_options
        else "pg_query_parse_protobuf(input)"
    )
    return f'''/* Generated by tools/import_upstream.py. */
#include "pg_query.h"

#include <stdlib.h>

#if defined(_WIN32) || defined(_WIN64)
# define FLYOLOGY_EXPORT __declspec(dllexport)
#else
# define FLYOLOGY_EXPORT __attribute__((visibility("default")))
#endif

typedef struct Flyology_PG{major}_Result
{{
    PgQueryProtobufParseResult result;
}} Flyology_PG{major}_Result;

FLYOLOGY_EXPORT void *
flyology_pg{major}_parse(const char *input, int parser_options)
{{
    Flyology_PG{major}_Result *holder = malloc(sizeof(*holder));
    if (holder == NULL)
        return NULL;
    holder->result = {call};
    return holder;
}}

FLYOLOGY_EXPORT const char *
flyology_pg{major}_data(void *handle)
{{
    Flyology_PG{major}_Result *holder = handle;
    return holder == NULL ? NULL : holder->result.parse_tree.data;
}}

FLYOLOGY_EXPORT size_t
flyology_pg{major}_length(void *handle)
{{
    Flyology_PG{major}_Result *holder = handle;
    return holder == NULL ? 0 : holder->result.parse_tree.len;
}}

FLYOLOGY_EXPORT const char *
flyology_pg{major}_error(void *handle)
{{
    Flyology_PG{major}_Result *holder = handle;
    return holder == NULL || holder->result.error == NULL
      ? NULL : holder->result.error->message;
}}

FLYOLOGY_EXPORT int
flyology_pg{major}_error_position(void *handle)
{{
    Flyology_PG{major}_Result *holder = handle;
    return holder == NULL || holder->result.error == NULL
      ? 0 : holder->result.error->cursorpos;
}}

FLYOLOGY_EXPORT void
flyology_pg{major}_free(void *handle)
{{
    Flyology_PG{major}_Result *holder = handle;
    if (holder != NULL)
    {{
        pg_query_free_protobuf_parse_result(holder->result);
        free(holder);
    }}
}}
'''


def minimal_header(major: int, pg_version: str, has_options: bool) -> str:
    options_declaration = (
        "PgQueryProtobufParseResult pg_query_parse_protobuf_opts"
        "(const char* input, int parser_options);\n"
        if has_options else ""
    )
    return f'''#ifndef PG_QUERY_H
#define PG_QUERY_H

#include <stdbool.h>
#include <stdint.h>
#include <sys/types.h>

typedef struct {{
    char* message;
    char* funcname;
    char* filename;
    int lineno;
    int cursorpos;
    char* context;
}} PgQueryError;

typedef struct {{
    size_t len;
    char* data;
}} PgQueryProtobuf;

typedef struct {{
    PgQueryProtobuf parse_tree;
    char* stderr_buffer;
    PgQueryError* error;
}} PgQueryProtobufParseResult;

typedef enum {{
    PG_QUERY_PARSE_DEFAULT = 0,
    PG_QUERY_PARSE_TYPE_NAME,
    PG_QUERY_PARSE_PLPGSQL_EXPR,
    PG_QUERY_PARSE_PLPGSQL_ASSIGN1,
    PG_QUERY_PARSE_PLPGSQL_ASSIGN2,
    PG_QUERY_PARSE_PLPGSQL_ASSIGN3
}} PgQueryParseMode;

#define PG_QUERY_PARSE_MODE_BITS 4
#define PG_QUERY_PARSE_MODE_BITMASK ((1 << PG_QUERY_PARSE_MODE_BITS) - 1)
#define PG_QUERY_DISABLE_BACKSLASH_QUOTE 16
#define PG_QUERY_DISABLE_STANDARD_CONFORMING_STRINGS 32
#define PG_QUERY_DISABLE_ESCAPE_STRING_WARNING 64

#ifdef __cplusplus
extern "C" {{
#endif

PgQueryProtobufParseResult pg_query_parse_protobuf(const char* input);
{options_declaration}void pg_query_free_protobuf_parse_result(PgQueryProtobufParseResult result);
void pg_query_exit(void);
void pg_query_init(void);

#define PG_MAJORVERSION "{major}"
#define PG_VERSION "{pg_version}"
#define PG_VERSION_NUM {int(major) * 10_000 + int(pg_version.split('.', 1)[1]):06d}

#ifdef __cplusplus
}}
#endif

#endif
'''


def parse_makefile(source: Path) -> tuple[str, str]:
    text = (source / "Makefile").read_text()
    pg_match = re.search(r"^PG_VERSION\s*=\s*(\S+)", text, re.MULTILINE)
    version_match = re.search(r"^VERSION\s*=\s*(\S+)", text, re.MULTILINE)
    if not pg_match or not version_match:
        raise ValueError(f"version metadata is missing in {source / 'Makefile'}")
    return pg_match.group(1), version_match.group(1)


def import_version(
    source: Path,
    destination: Path,
    major: int,
    archive: Path | None,
    release: str | None,
) -> None:
    pg_version, makefile_version = parse_makefile(source)
    extraction_version = release or makefile_version
    if int(pg_version.split(".", 1)[0]) != major:
        raise ValueError(f"{source} contains PostgreSQL {pg_version}, expected {major}")

    previous_hash = "not-recorded"
    previous_provenance = destination / "UPSTREAM.toml"
    if archive is None and previous_provenance.exists():
        match = re.search(
            r'^archive_sha256\s*=\s*"([^"]+)"',
            previous_provenance.read_text(),
            re.MULTILINE,
        )
        if match:
            previous_hash = match.group(1)

    if destination.exists():
        shutil.rmtree(destination)
    (destination / "src").mkdir(parents=True)

    shutil.copy2(source / "LICENSE", destination / "LICENSE")

    for name in (
        "pg_query.c",
        "pg_query_internal.h",
        "pg_query_outfuncs.h",
        "pg_query_outfuncs_protobuf.c",
    ):
        shutil.copy2(source / "src" / name, destination / "src" / name)

    parse_source = (source / "src" / "pg_query_parse.c").read_text()
    (destination / "src" / "pg_query_parse.c").write_text(thin_parse_source(parse_source))

    #  Newer releases carry extraction-only headers in src/include.  PostgreSQL
    #  14 and 15 keep everything beneath src/postgres/include instead.
    if (source / "src" / "include").exists():
        shutil.copytree(source / "src" / "include", destination / "src" / "include")
        retained_generated = {
            "pg_query_enum_defs.c",
            "pg_query_outfuncs_conds.c",
            "pg_query_outfuncs_defs.c",
            "pg_query_pg_type.c",
            "pg_query_proctup_attrs.h",
        }
        for path in (destination / "src" / "include").iterdir():
            if path.is_file() and path.name not in retained_generated:
                path.unlink()
    else:
        (destination / "src" / "include").mkdir()
        #  The protobuf emitter includes these generated implementation fragments
        #  directly.  In the 14 and 15 layouts they live beside the emitter.
        for name in (
            "pg_query_enum_defs.c",
            "pg_query_outfuncs_conds.c",
            "pg_query_outfuncs_defs.c",
        ):
            shutil.copy2(source / "src" / name, destination / "src" / "include" / name)
    shutil.copytree(
        source / "src" / "postgres",
        destination / "src" / "postgres",
        ignore=shutil.ignore_patterns("*.o", "*.a", "*.dylib", "*.so"),
    )
    (destination / "protobuf").mkdir()
    for name in ("pg_query.pb-c.c", "pg_query.pb-c.h"):
        shutil.copy2(source / "protobuf" / name, destination / "protobuf" / name)
    shutil.copytree(
        source / "vendor" / "protobuf-c",
        destination / "vendor" / "protobuf-c",
        ignore=shutil.ignore_patterns("*.o", "*.a", "*.dylib", "*.so"),
    )

    #  macOS 15.4 added strchrnul with a signature that conflicts with the
    #  PostgreSQL 14--16 fallback.  PostgreSQL 17 solved this by namespacing
    #  its fallback; apply the equivalent compatibility shim to old majors.
    if major <= 16:
        snprintf = destination / "src" / "postgres" / "src_port_snprintf.c"
        text = snprintf.read_text()
        marker = "#ifndef HAVE_STRCHRNUL\n"
        shim = (
            "#if defined(__APPLE__)\n"
            "#undef HAVE_STRCHRNUL\n"
            "#define strchrnul pg_strchrnul\n"
            "#endif\n"
        )
        if marker not in text:
            raise ValueError(f"strchrnul compatibility marker is missing in {snprintf}")
        if "#define strchrnul pg_strchrnul" not in text:
            snprintf.write_text(text.replace(marker, shim + marker, 1))
    shutil.copy2(source / "protobuf" / "pg_query.proto", destination / "pg_query.proto")

    # PL/pgSQL is a separate language parser and is intentionally outside this
    # crate.  Its extracted objects also pull in catalog-analysis helpers that
    # the raw SQL parser does not use.
    for path in (destination / "src" / "postgres").glob("src_pl_plpgsql_*"):
        path.unlink()
    for path in (
        destination / "src" / "postgres" / "include" / "plpgsql.h",
    ):
        if path.exists():
            path.unlink()

    header = (source / "pg_query.h").read_text()
    has_options = "pg_query_parse_protobuf_opts" in header
    (destination / "pg_query.h").write_text(
        minimal_header(major, pg_version, has_options)
    )
    (destination / f"flyology_pg{major}_wrapper.c").write_text(wrapper(major, has_options))

    archive_hash = digest(archive) if archive else previous_hash
    (destination / "UPSTREAM.toml").write_text(
        f'''postgresql_major = {major}
postgresql_release = "{pg_version}"
libpg_query_release = "{extraction_version}"
libpg_query_makefile_release = "{makefile_version}"
archive_sha256 = "{archive_hash}"
source = "https://github.com/pganalyze/libpg_query"
postgresql_source = "https://ftp.postgresql.org/pub/source/v{pg_version}/"
included_components = [
  "raw PostgreSQL parser extraction",
  "src/pg_query_outfuncs_protobuf.c",
  "pg_query.proto",
  "protobuf/pg_query.pb-c.c",
  "protobuf/pg_query.pb-c.h",
  "vendor/protobuf-c/protobuf-c.c",
  "vendor/protobuf-c/protobuf-c.h",
]
excluded_apis = [
  "JSON serialization",
  "fingerprinting",
  "normalization",
  "deparsing",
  "PL/pgSQL parsing",
  "query splitting and scanning",
]
'''
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--major", type=int, choices=VERSIONS, required=True)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--destination", type=Path, required=True)
    parser.add_argument("--archive", type=Path)
    parser.add_argument(
        "--libpg-query-release",
        help="release tag used for the archive (some historical Makefiles are stale)",
    )
    args = parser.parse_args()
    import_version(
        args.source.resolve(),
        args.destination.resolve(),
        args.major,
        args.archive,
        args.libpg_query_release,
    )


if __name__ == "__main__":
    main()
